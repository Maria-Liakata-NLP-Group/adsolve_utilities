import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import pytest

from evaluation_api import runner
from evaluation_api.config import load_settings

RESULTS = {"intra_nli": {"document_level": [1.0], "mean": 1.0}, "document_ids": ["doc1"]}


def _job_dir(tmp_path) -> Path:
    job_dir = tmp_path / "job"
    job_dir.mkdir()
    (job_dir / "llm_summaries.json").write_text(json.dumps({"doc1": "a"}))
    (job_dir / "gold_summaries.json").write_text(json.dumps({"doc1": ""}))
    return job_dir


def _fake_run(results=RESULTS, returncode=0, stderr=""):
    """Stand in for subprocess.run: write the results file the worker expects."""
    calls = []

    def run(argv, **kwargs):
        calls.append((argv, kwargs))
        if returncode == 0:
            output_index = argv.index("--output_file") + 1
            Path(argv[output_index]).write_text(json.dumps(results))
        return subprocess.CompletedProcess(argv, returncode, stdout="", stderr=stderr)

    run.calls = calls
    return run


def test_run_local_bundle_returns_the_results_file_contents(tmp_path):
    job_dir = _job_dir(tmp_path)
    output = runner.run_local_bundle("my_run", ["intra_nli"], job_dir, 60, run=_fake_run())
    assert output == RESULTS


def test_run_local_bundle_writes_the_generated_script(tmp_path):
    job_dir = _job_dir(tmp_path)
    runner.run_local_bundle("my_run", ["intra_nli"], job_dir, 60, run=_fake_run())
    script = job_dir / "my_run_evaluation.py"
    assert script.exists()
    assert script.read_text().startswith("# Generated by generate_bundle.py")


def test_subprocess_gets_pythonpath_pointing_at_evaluation_bundles(tmp_path):
    """Without this the generated script's `from metrics.fc import ...` fails."""
    job_dir = _job_dir(tmp_path)
    run = _fake_run()
    runner.run_local_bundle("my_run", ["intra_nli"], job_dir, 60, run=run)
    _, kwargs = run.calls[0]
    assert kwargs["env"]["PYTHONPATH"].endswith("evaluation_bundles")


def test_posts_flag_is_passed_only_when_a_metric_needs_posts(tmp_path):
    job_dir = _job_dir(tmp_path)
    (job_dir / "posts.json").write_text(json.dumps({"doc1": ["p"]}))

    run = _fake_run()
    runner.run_local_bundle("my_run", ["intra_nli"], job_dir, 60, run=run)
    assert "--posts" not in run.calls[0][0]

    run = _fake_run(results={"mhic": {"document_level": [1.0], "mean": 1.0},
                             "document_ids": ["doc1"]})
    runner.run_local_bundle("my_run", ["mhic"], job_dir, 60, run=run)
    assert "--posts" in run.calls[0][0]


def test_non_zero_exit_raises_with_the_stderr_tail(tmp_path):
    job_dir = _job_dir(tmp_path)
    run = _fake_run(returncode=1, stderr="CUDA out of memory")
    with pytest.raises(runner.BundleError) as excinfo:
        runner.run_local_bundle("my_run", ["intra_nli"], job_dir, 60, run=run)
    assert "CUDA out of memory" in str(excinfo.value)


def test_timeout_raises_a_bundle_error(tmp_path):
    job_dir = _job_dir(tmp_path)

    def run(argv, **kwargs):
        raise subprocess.TimeoutExpired(argv, 60)

    with pytest.raises(runner.BundleError) as excinfo:
        runner.run_local_bundle("my_run", ["intra_nli"], job_dir, 60, run=run)
    assert "timed out" in str(excinfo.value).lower()


def test_execute_runs_standard_metrics_locally(tmp_path):
    settings = load_settings({"METRIC_JOB_ROOT": str(tmp_path)})
    output = runner.execute("my_run", ["intra_nli"], _job_dir(tmp_path), settings,
                            run=_fake_run())
    assert output == RESULTS


def test_execute_rejects_an_unimplemented_environment(tmp_path):
    settings = load_settings({"METRIC_ENV_GREENSCORE_URL": "http://green:8000"})
    with pytest.raises(runner.UnsupportedEnvironmentError):
        runner.execute("my_run", ["green_score"], _job_dir(tmp_path), settings,
                       run=_fake_run())
